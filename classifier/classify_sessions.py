"""Attacker-behaviour classifier + MITRE ATT&CK mapping for sessions seen at the decoy.

Sessions are generated by the simulated attacker profiles in PQCDeceptionEnv
(plus legitimate clients), with every request logged as the decoy would see it.
RF and XGBoost are evaluated with 5-fold stratified CV, repeated for the 5 seeds.
Writes eval/classifier_results.md
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import entropy
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, f1_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.preprocessing import LabelEncoder
from xgboost import XGBClassifier

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "rl-env"))
from pqc_deception_env import PQCDeceptionEnv, PROFILES, ROUTE_DECOY_HI  # noqa: E402

SEEDS = [42, 123, 456, 789, 1024]
SESSIONS_PER_CLASS = 400

ATTACK_MAP = {
    "scanner":    "TA0043 Reconnaissance / T1595 Active Scanning",
    "downgrader": "TA0005 Defense Evasion / T1562.010 Downgrade Attack",
    "flooder":    "TA0040 Impact / T1499 Endpoint Denial of Service",
    "apt":        "Multi-stage: TA0043 -> TA0005 -> TA0040",
    "stealthy":   "TA0043 Reconnaissance / T1595 via protocol-conformant probing",
    "legit":      "benign",
}


def features(reqs, rates):
    reqs = np.asarray(reqs)
    counts = np.bincount(reqs, minlength=4)
    frac = counts / max(1, len(reqs))
    trans = np.sum(reqs[1:] != reqs[:-1]) if len(reqs) > 1 else 0
    return [len(reqs), *counts, *frac, np.mean(rates), np.max(rates),
            entropy(frac + 1e-12), trans, reqs[0]]


FEATURES = ["n_req", "n_banner", "n_handshake", "n_downgrade", "n_flood",
            "f_banner", "f_handshake", "f_downgrade", "f_flood",
            "mean_rate", "max_rate", "req_entropy", "n_transitions", "first_req"]


def generate(seed):
    rng = np.random.default_rng(seed)
    X, y = [], []
    for prof in PROFILES:
        env = PQCDeceptionEnv(profile=prof, legit_rate=0.0, detect_scale=0.0)
        for i in range(SESSIONS_PER_CLASS):
            env.reset(seed=seed * 100_000 + len(y))
            reqs, rates = [], []
            for _ in range(int(rng.integers(3, 30))):
                reqs.append(env.req)
                rates.append(env.src_rate)
                env.step(ROUTE_DECOY_HI)
            X.append(features(reqs, rates))
            y.append(prof)
    for i in range(SESSIONS_PER_CLASS):  # legit: a few handshakes at low rate
        n = int(rng.integers(1, 6))
        X.append(features([1] * n, rng.uniform(0.0, 0.3, n)))
        y.append("legit")
    return pd.DataFrame(X, columns=FEATURES), np.array(y)


def main():
    rows, reports = [], []
    for seed in SEEDS:
        X, y = generate(seed)
        le = LabelEncoder().fit(y)
        yy = le.transform(y)
        cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
        models = {"RF": RandomForestClassifier(n_estimators=200, n_jobs=2, random_state=seed),
                  "XGB": XGBClassifier(n_estimators=200, max_depth=6, n_jobs=2,
                                       random_state=seed, eval_metric="mlogloss")}
        for name, m in models.items():
            pred = cross_val_predict(m, X, yy, cv=cv)
            rows.append(dict(seed=seed, model=name, macro_f1=f1_score(yy, pred, average="macro")))
            if seed == SEEDS[0]:
                reports.append(f"### {name} (seed {seed})\n```\n"
                               + classification_report(yy, pred, target_names=le.classes_, digits=3)
                               + "```")
    r = pd.DataFrame(rows)
    summary = r.groupby("model").macro_f1.agg(["mean", "std"]).round(4)
    mapping = pd.DataFrame(ATTACK_MAP.items(), columns=["class", "MITRE ATT&CK"])
    text = ("## Macro-F1 over 5 seeds (5-fold stratified CV each)\n\n" + summary.to_markdown()
            + "\n\n" + "\n\n".join(reports) + "\n\n## ATT&CK mapping\n\n" + mapping.to_markdown(index=False)
            + "\n\nNote: sessions come from the simulated attacker profiles, so these scores validate the "
              "pipeline on the modelled behaviours, not detection of real-world attackers.")
    (ROOT / "eval" / "classifier_results.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
